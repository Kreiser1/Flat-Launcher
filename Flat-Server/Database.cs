namespace Flat_Server.Database
{
	using Dapper;

	using Npgsql;

	public class DatabaseException : Exception
	{
		public DatabaseException() : base() { }
		public DatabaseException(string message) : base(message) { }
		public DatabaseException(string message, Exception? innerException)
			: base(message, innerException) { }
	}

	public static class Database
	{
		public static string ConnectionString { get; private set; }

		static Database()
		{
			ConnectionString = System.Configuration.ConfigurationManager.ConnectionStrings["DefaultConnection"].ConnectionString;
		}

		private static async Task<NpgsqlConnection> ConnectAsync()
		{
			try
			{
				NpgsqlConnection connection = new(ConnectionString);
				await connection.OpenAsync();
				return connection;
			}
			catch (NpgsqlException) { throw new DatabaseException("Не удалось подключиться к базе данных."); }
		}

		public static async Task<T> QueryAsync<T>(Func<NpgsqlConnection, Task<T>> body)
		{
			await using NpgsqlConnection connection = await ConnectAsync();
			return await body(connection);
		}

		public static async Task<T> TransactAsync<T>(Func<NpgsqlConnection, Task<T>> body)
		{
			NpgsqlConnection connection = await ConnectAsync();

			await using (connection)
			{
				await using NpgsqlTransaction transaction = await connection.BeginTransactionAsync();

				try
				{
					T result = await body(connection);
					await transaction.CommitAsync();
					return result;
				}
				catch
				{
					await transaction.RollbackAsync();
					throw;
				}
			}
		}

